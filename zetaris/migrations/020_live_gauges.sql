-- Live PEGELONLINE gauges for Zetaris.
--
-- UNTESTED against a running Zetaris. Verify this file on Mihir's local
-- Zetaris (Docker Desktop, Windows, PowerShell 5). Do not join commands
-- with &&. Use python, not py.
--
-- python tasks.py zetaris-sync is still a stub and applies nothing. Paste
-- these statements into the Zetaris SQL editor, one statement at a time.
-- The separator is a line that is exactly `-- statement`.
--
-- Idempotency, from the command reference checked on 2026-10-23:
-- CREATE DATASOURCE, CREATE LIGHTNING DATABASE, CREATE LIGHTNING REST TABLE,
-- and CREATE SCHEMASTORE CONTAINER have no IF NOT EXISTS form. CREATE OR
-- REPLACE is documented for SCHEMASTORE VIEW. If a CREATE answers that the
-- object already exists, skip that statement and run the verify SELECT.
-- Do not edit this file after it has been applied. Add 021_....sql instead.
--
-- Credentials are ${VAR} placeholders. Replace them in the editor from
-- ingestion/.env. Do not commit the filled statement. The poller itself
-- reads ingestion/live/.env and does not use the JDBC URL.
--
-- JDBC URL, currentSchema=live so the tables register as gauge_station and
-- gauge_measurement (not live.gauge_station). Pick one:
--   Zetaris container joined to floodsense-app-net:
--     jdbc:postgresql://pgvector:5432/floodsense?currentSchema=live
--   Docker Desktop on Windows, published host port (bound to 127.0.0.1):
--     jdbc:postgresql://host.docker.internal:15432/floodsense?currentSchema=live
-- If host.docker.internal cannot open that loopback port, use the network
-- join. Do not republish Postgres on 0.0.0.0. Service DNS name: pgvector.
-- Port inside the network is 5432. Host port is 15432.
--
-- The REST example is one station object (Bonn, uuid verified 2026-10-23).
-- Shape: top-level JSON object, timeseries array of structs. The view
-- explodes that array (Zetaris REST companion, case 1). W is water level.
-- Q (discharge) is filtered out. If inference drops gaugeZero or the state
-- fields because Q rows omit them, add &timeseries=W to the endpoint and
-- recreate the REST table.
-- A REST table may call PEGELONLINE again on every query. That behaviour
-- was not re-checked here. CACHE TABLE is session-scoped and is not a
-- statement in this file.
--
-- Run the poller before the JDBC verify SELECTs. An empty table is still
-- a successful query. Licence on the JDBC rows is DL-DE->Zero-2.0.
-- live.gauge_http_cache is poller state and is not registered.

-- statement
CREATE DATASOURCE floodsense_pg DESCRIBE BY "FloodSense Postgres live gauges" OPTIONS (
  jdbcdriver "org.postgresql.Driver",
  jdbcurl "${FLOODSENSE_PG_JDBC_URL}",
  username "${POSTGRES_USER}",
  password "${POSTGRES_PASSWORD}",
  fetchsize "1000"
)

-- statement
REGISTER DATASOURCE TABLES ("gauge_station", "gauge_measurement") FROM floodsense_pg

-- statement
SHOW DATASOURCE TABLES floodsense_pg

-- statement
SELECT station_uuid, shortname, water_shortname, km, licence, fetched_at
FROM floodsense_pg.gauge_station
ORDER BY km

-- statement
SELECT station_uuid, timeseries, ts_utc, value, unit, source, licence
FROM floodsense_pg.gauge_measurement
ORDER BY ts_utc DESC
LIMIT 20

-- statement
CREATE LIGHTNING DATABASE pegelonline_rest DESCRIBE BY "PEGELONLINE REST station Bonn"

-- statement
CREATE LIGHTNING REST TABLE bonn_station FROM pegelonline_rest REQUEST (
  endpoint "https://pegelonline.wsv.de/webservices/rest-api/v2/stations/593647aa-9fea-43ec-a7d6-6476a76ae868.json?includeTimeseries=true&includeCurrentMeasurement=true",
  method "GET",
  http_encoding "URLENCODED",
  response_type "JSON"
) HEADER (
  Accept "application/json",
  Accept-Encoding "gzip",
  User-Agent "FloodSenseEU/0.1 PEGELONLINE"
) BODY ()

-- statement
CREATE SCHEMASTORE CONTAINER floodsense_live

-- statement
CREATE OR REPLACE SCHEMASTORE VIEW pegelonline_bonn_w WITH CONTAINER floodsense_live AS
SELECT
  uuid AS station_uuid,
  number AS station_number,
  shortname,
  longname,
  km,
  agency,
  latitude,
  longitude,
  water.shortname AS water_shortname,
  water.longname AS water_longname,
  series.shortname AS timeseries,
  series.longname AS timeseries_longname,
  series.unit AS unit,
  series.equidistance AS equidistance,
  series.`currentMeasurement`.timestamp AS measured_at,
  CAST(series.`currentMeasurement`.value AS DOUBLE) AS water_level_cm,
  series.`currentMeasurement`.`stateMnwMhw` AS state_mnw_mhw,
  series.`currentMeasurement`.`stateNswHsw` AS state_nsw_hsw,
  series.`gaugeZero`.value AS gauge_zero_value,
  series.`gaugeZero`.unit AS gauge_zero_unit,
  series.`gaugeZero`.`validFrom` AS gauge_zero_valid_from
FROM pegelonline_rest.bonn_station
LATERAL VIEW explode(timeseries) AS series
WHERE series.shortname = 'W'

-- statement
SELECT
  station_uuid,
  shortname,
  timeseries,
  measured_at,
  water_level_cm,
  state_mnw_mhw
FROM floodsense_live.pegelonline_bonn_w
